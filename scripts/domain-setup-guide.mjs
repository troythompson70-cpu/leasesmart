#!/usr/bin/env node
/**
 * Sprint F1 — GoDaddy + GitHub Pages domain setup guide generator
 */
import { writeFileSync, mkdirSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const DOMAIN_GUIDE_PATH = join(ROOT, 'master-vault', 'DOMAIN-SETUP-GUIDE.md');

export function buildDomainSetupGuide() {
  return [
    '# LeaseSmart Domain Setup Guide',
    '',
    '**TGT Technologies Inc.** — Plain English steps for `leasesmart.tgttechnologies.com` on GitHub Pages via GoDaddy.',
    '',
    '> Generated by `scripts/domain-setup-guide.mjs` — Sprint F1 skeleton.',
    '',
    '## Overview',
    '',
    'You will point a **CNAME** record at GoDaddy to GitHub Pages, then tell GitHub which custom domain to serve.',
    '',
    '## Step 1 — GitHub Pages settings',
    '',
    '1. Open your LeaseSmart repo on GitHub → **Settings** → **Pages**.',
    '2. Under **Build and deployment**, set Source to **GitHub Actions** (or branch `main` / root if using static deploy).',
    '3. Under **Custom domain**, enter: `leasesmart.tgttechnologies.com`',
    '4. Click **Save**. GitHub may show “DNS check in progress”.',
    '5. Enable **Enforce HTTPS** once the certificate is issued (can take up to 24 hours).',
    '',
    '## Step 2 — GoDaddy DNS (CNAME)',
    '',
    '1. Log in to GoDaddy → **My Products** → your domain `tgttechnologies.com` → **DNS**.',
    '2. Add or edit a **CNAME** record:',
    '   - **Type:** CNAME',
    '   - **Name / Host:** `leasesmart` (subdomain only — not the full URL)',
    '   - **Value / Points to:** `troythompson70-cpu.github.io` (replace with your GitHub Pages default host if different)',
    '   - **TTL:** 1 hour (or default)',
    '3. Remove conflicting **A** records for the same `leasesmart` host if any exist.',
    '4. Save changes.',
    '',
    '## Step 3 — Repo CNAME file (if needed)',
    '',
    'Some setups use a `CNAME` file in the repo root containing:',
    '',
    '```',
    'leasesmart.tgttechnologies.com',
    '```',
    '',
    'LeaseSmart may already use `_redirects` or workflow deploy — match your existing Pages workflow.',
    '',
    '## Step 4 — Expected propagation time',
    '',
    '- **DNS:** 15 minutes to 48 hours (often under 1 hour).',
    '- **GitHub certificate:** up to 24 hours after DNS resolves correctly.',
    '- Use [https://dnschecker.org](https://dnschecker.org) for `leasesmart.tgttechnologies.com` CNAME lookup.',
    '',
    '## Step 5 — Verify it worked',
    '',
    '1. Run: `dig leasesmart.tgttechnologies.com CNAME +short` — should show your `*.github.io` target.',
    '2. Visit `https://leasesmart.tgttechnologies.com` — should load LeaseSmart (not GoDaddy parking).',
    '3. In GitHub Pages settings, confirm **“DNS check successful”** and HTTPS is active.',
    '4. Hard-refresh or open in private window to avoid stale DNS cache.',
    '',
    '## Troubleshooting',
    '',
    '- **404 from GitHub:** Custom domain saved but repo not deployed — run Pages workflow.',
    '- **Certificate pending:** Wait; do not disable HTTPS enforcement prematurely.',
    '- **Wrong site:** CNAME points to wrong GitHub user/org Pages host.',
    '',
    '## Security notes',
    '',
    '- Never commit API keys, VAPID keys, or Supabase service role keys.',
    '- Beta/demo builds only until legal and billing sprints are attorney-approved.',
    '',
  ].join('\n');
}

export function writeDomainSetupGuide() {
  mkdirSync(join(ROOT, 'master-vault'), { recursive: true });
  const body = buildDomainSetupGuide();
  writeFileSync(DOMAIN_GUIDE_PATH, body + '\n', 'utf8');
  return { path: DOMAIN_GUIDE_PATH, lines: body.split('\n').length };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const r = writeDomainSetupGuide();
  console.log(JSON.stringify({ ok: true, ...r }, null, 2));
}
